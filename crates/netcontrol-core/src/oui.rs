/// Resolves the OUI vendor for a MAC address, or `None` if the prefix is unknown.
///
/// Mirrors `OuiDatabase.Lookup(byte[])`: requires at least 3 bytes.
pub fn lookup(mac: &[u8]) -> Option<&'static str> {
    if mac.len() < 3 {
        return None;
    }
    let key = ((mac[0] as u32) << 16) | ((mac[1] as u32) << 8) | (mac[2] as u32);
    // Binary search would require a sorted table; the original uses a hash map.
    // A linear scan over ~340 entries is trivial, but we use a lazily-built map
    // for O(1) parity with the C# FrozenDictionary.
    lookup_map().get(&key).copied()
}

use std::collections::HashMap;
use std::sync::OnceLock;

fn lookup_map() -> &'static HashMap<u32, &'static str> {
    static MAP: OnceLock<HashMap<u32, &'static str>> = OnceLock::new();
    MAP.get_or_init(|| OUI_TABLE.iter().copied().collect())
}

/// Detects whether a MAC address is locally administered (randomized).
///
/// Modern iOS 14+ and Android 10+ randomize MAC addresses for privacy.
/// Bit 1 of the first byte (the "locally administered" bit) is set.
///
/// Mirrors `OuiDatabase.IsRandomizedMac`.
pub fn is_randomized_mac(mac: &[u8]) -> bool {
    if mac.is_empty() {
        return false;
    }
    (mac[0] & 0x02) != 0
}
